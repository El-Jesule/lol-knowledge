"""Survival mechanics: shields, Grievous Wounds, heal/shield power and effect healing.

Pure rules documented in ``lol-knowledge/mechanics/survival.md`` (MEC-04 to MEC-07):
- Heal and shield power (``heal_and_shield_power``) multiplies direct heals, drain
  and shields, but does not apply to life steal or omnivamp.
- Revitalize's <40% HP bonus (+10%) multiplies all healing (including life steal
  and omnivamp) and shields separately from heal and shield power.
- Grievous Wounds (-40%, non-stacking) reduces all healing (life steal, omnivamp,
  drain and direct heals) and never reduces shields.
- Target shields absorb post-mitigation damage by type (``normal``, ``physical``,
  ``magic``) without altering health-based formulas or executes.
"""

from __future__ import annotations

from dataclasses import dataclass
from fractions import Fraction

from .damage import DamageType
from .errors import StatsError
from .stats import Label

SHIELD_TYPES = frozenset({"normal", "physical", "magic"})
GRIEVOUS_WOUNDS_REDUCTION = Fraction(2, 5)  # 40 %, non-stacking (Grievous_Wounds rev 3969410)


@dataclass(frozen=True)
class HealEvent:
    """One direct healing event generated by an item or rune effect (not vamp)."""

    source: str
    raw: Fraction
    amount: Fraction
    uses_hsp: bool
    grievous_applied: bool
    label: Label
    notes: tuple[str, ...] = ()


@dataclass(frozen=True)
class ShieldEvent:
    """One shield granted to the attacker by an item or rune effect."""

    source: str
    raw: Fraction
    amount: Fraction
    shield_type: str = "normal"
    duration: Fraction | None = None
    label: Label = Label.DERIVED
    notes: tuple[str, ...] = ()


def validate_shield_type(shield_type: str) -> str:
    if shield_type not in SHIELD_TYPES:
        allowed = ", ".join(sorted(SHIELD_TYPES))
        raise StatsError(f"unknown shield type {shield_type!r} (use {allowed})")
    return shield_type


def shield_blocks_damage_type(shield_type: str, damage_type: DamageType) -> bool:
    if shield_type == "normal":
        return True
    if shield_type == "physical":
        return damage_type is DamageType.PHYSICAL
    if shield_type == "magic":
        return damage_type is DamageType.MAGIC
    return False


def absorb_shield(
    damage: Fraction,
    damage_type: DamageType,
    shield: Fraction,
    shield_type: str = "normal",
    *,
    bypass_shield: bool = False,
) -> tuple[Fraction, Fraction]:
    """Return ``(shield_absorbed, health_damage)`` for one post-mitigation part."""
    if (
        bypass_shield
        or damage <= 0  # pragma: no mutate
        or shield <= 0  # pragma: no mutate
        or not shield_blocks_damage_type(shield_type, damage_type)
    ):
        return Fraction(0), damage
    absorbed = min(shield, damage)
    return absorbed, damage - absorbed


def scale_healing(
    raw: Fraction,
    *,
    hsp: Fraction = Fraction(0),
    revitalize_amp: Fraction = Fraction(0),
    grievous: Fraction = Fraction(0),
    uses_hsp: bool = True,
) -> Fraction:
    """Apply heal/shield power, Revitalize <40% amp and Grievous Wounds multiplicatively."""
    factor = Fraction(1)
    if uses_hsp and hsp:
        factor *= 1 + hsp
    if revitalize_amp:
        factor *= 1 + revitalize_amp
    if grievous:
        factor *= max(Fraction(0), 1 - grievous)
    return raw * factor


def scale_shield(
    raw: Fraction,
    *,
    hsp: Fraction = Fraction(0),
    revitalize_amp: Fraction = Fraction(0),
) -> Fraction:
    """Apply heal/shield power and Revitalize <40% amp to a shield (ignores Grievous Wounds)."""
    factor = Fraction(1)
    if hsp:
        factor *= 1 + hsp
    if revitalize_amp:
        factor *= 1 + revitalize_amp
    return raw * factor


def absorb_life_heal(level: int) -> Fraction:
    """Absorb Life (9101) heal by champion level (Template:Rune_data_Absorb_Life rev 3997095).

    1 at level 1, +0.25/lvl up to level 5 (2), +1/lvl up to level 10 (7),
    +2/lvl from level 11 onwards (23 at level 18).
    """
    if level <= 1:  # pragma: no mutate
        return Fraction(1)
    if level <= 5:  # pragma: no mutate
        return Fraction(1) + Fraction(1, 4) * (level - 1)
    if level <= 10:  # pragma: no mutate
        return Fraction(2) + Fraction(level - 5)
    return Fraction(7) + Fraction(2) * (level - 10)
